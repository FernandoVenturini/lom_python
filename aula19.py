# OPERADORES DE COMPARACAO:

# == (igual a)
# != (diferente de)
# > (maior que)
# < (menor que)
# >= (maior ou igual a)
# <= (menor ou igual a)

# Exemplo:
a = 10
b = 20
print(a == b)  # False
print(a != b)  # True
print(a > b)   # False
print(a < b)   # True
print(a >= b)  # False
print(a <= b)  # True